function resolveLogo(logoPath?: string): string | undefined {
  if (!logoPath) return undefined;
  if (logoPath.startsWith('http')) return logoPath;
  const fileName = logoPath.split('/').pop();
  return fileName ? (universityLogos[fileName] || logoPath) : logoPath;
}

